#!/usr/bin/env bash
# Copy Squeak's iPhone screens (SqueakUI) and their core (SqueakCore) into
# another app as one self-contained Swift package, so that app can show
# Squeak as a tab: `SqueakRootView()`.
#
#   ios/scripts/vendor-into.sh <dest-dir>      # e.g. ../snof/ios/SqueakKit
#
# The copy is generated: edit here, then re-run this. It carries no tests or
# tools, and a VENDORED.md naming the Squeak commit it came from.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
dest="${1:?usage: vendor-into.sh <dest-dir>}"
src="$here/SqueakCore/Sources"
commit="$(git -C "$here" rev-parse --short HEAD)"
dirty="$(git -C "$here" status --porcelain -- SqueakCore | head -1)"

rm -rf "$dest"
mkdir -p "$dest/Sources"
cp -R "$src/SqueakCore" "$src/SqueakUI" "$dest/Sources/"
cat > "$dest/Package.swift" <<'SWIFT'
// swift-tools-version:5.9
// Generated by Squeak's ios/scripts/vendor-into.sh — do not edit here.
import PackageDescription

let package = Package(
    name: "SqueakKit",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [.library(name: "SqueakUI", targets: ["SqueakUI"])],
    targets: [
        .target(name: "SqueakCore"),
        .target(name: "SqueakUI", dependencies: ["SqueakCore"], resources: [.process("Resources")]),
    ]
)
SWIFT
cat > "$dest/VENDORED.md" <<MD
# SqueakKit (vendored)

Squeak's iPhone screens, embedded here as a tab (\`SqueakRootView()\`).
Generated from Squeak commit \`$commit\`${dirty:+ (with uncommitted changes)} by
\`ios/scripts/vendor-into.sh\` in the Squeak repository. Do not edit this copy:
change Squeak, then re-run the script. See Squeak's docs/remote-channel.md
for what the tab does and why it is safe.
MD
echo "vendored SqueakKit ($commit) into $dest"
