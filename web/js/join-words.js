export async function joinWords(ownerKey, joinerKey, pondId) {
  const input = utf8(`squeak-pond-words-v1\n${ownerKey}\n${joinerKey}\n${pondId}`);
  const d = new Uint8Array(await globalThis.crypto.subtle.digest("SHA-256", input));
  return [JOIN_WORDS[d[0]], JOIN_WORDS[d[1]], JOIN_WORDS[d[2]]];
}
