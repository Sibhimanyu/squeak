public enum JoinWords {
    private static let domain = "squeak-pond-words-v1"

    /// The input, byte for byte: the domain tag, then the owner key, the joiner key and the pond id, each after a newline (UTF-8).
    public static func input(ownerKey: String, joinerKey: String, pondId: String) -> Data {
        Data("\(domain)\n\(ownerKey)\n\(joinerKey)\n\(pondId)".utf8)
    }

    /// Three words: the first three bytes of the SHA-256 index the list. A relay that swapped the owner's key shows other words.
    public static func derive(ownerKey: String, joinerKey: String, pondId: String) -> [String] {
        let digest = Array(SHA256.hash(data: input(ownerKey: ownerKey, joinerKey: joinerKey, pondId: pondId)))
        return (0..<3).map { list[Int(digest[$0])] }
    }

    /// "cobweb \u{00B7} elbow \u{00B7} igloo": how both screens say them.
    public static func line(_ words: [String]) -> String { words.joined(separator: " \u{00B7} ") }

