/// Six characters from an alphabet with no 0, O, 1, I or L, shown `K7P-4QD`.
public enum ShortCode {
    public static let alphabet = Set("23456789ABCDEFGHJKMNPQRSTUVWXYZ")
    public static let lifetime: TimeInterval = 10 * 60

    /// "k7p 4qd", "K7P-4QD", " k7p4qd " -> "K7P-4QD"; anything else (a long code, a typo, 0/O/1/I/L) -> nil.
    public static func normalize(_ input: String) -> String? {
        guard input.count <= 32 else { return nil }
        let bare = input.filter { !$0.isWhitespace && $0 != "-" }.uppercased()
        guard bare.count == 6, bare.allSatisfy({ alphabet.contains($0) }) else { return nil }
        return "\(bare.prefix(3))-\(bare.suffix(3))"
    }

    /// "9:42" left of a code's ten minutes; nil once it has lapsed.
    public static func countdown(until expiresAt: Date?, now: Date) -> String? {
        guard let expiresAt else { return nil }
        let left = Int(expiresAt.timeIntervalSince(now).rounded(.up))
        guard left > 0 else { return nil }
        return "\(left / 60):" + String(format: "%02d", left % 60)
    }
}
