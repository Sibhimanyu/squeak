/**
 * Film commands built and signed by the iPhone's own code (ios/SqueakCore `squeak-fixtures`), fed to the Mac's
 * real verifier and film checks. The fixture is regenerated by the phone's side: when it has no film commands
 * yet (an older fixture), these are skipped rather than failing the Mac's suite.
 */
type Signed = { box: string; sig: string; device: string };
const fixture = JSON.parse(
  fs.readFileSync(path.join(__dirname, "../../src/remote/fixtures", "swift-command.json"), "utf8"),
) as Record<string, unknown> & { madeAt: number; key: string; channelId: string; deviceId: string; publicKey: string };

const FILM = "film:0123456789abcdef";
const has = typeof fixture.filmChatCommand === "object";

function bridge() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "phone-interop-films-"));
  const configPath = path.join(dir, "remote.json");
  const config: RemoteConfig = {
    projectId: "squeak-test",
    channelId: fixture.channelId,
    key: fixture.key,
    devices: [{ id: fixture.deviceId, name: "iPhone", publicKey: fixture.publicKey, pairedAt: "2026-09-25T00:00:00Z" }],
  };
  fs.writeFileSync(configPath, JSON.stringify(config));
  const handled: FilmCommand[] = [];
  const pictures: Array<[string, string]> = [];
  const mediaFile = path.join(dir, "copy.m4a");
  fs.writeFileSync(mediaFile, Buffer.alloc(1000, 7));
  const films = {
    list: () => [],
    imageProject: (filmId: string, source: string) =>
      filmId === FILM && source === ".rasanai/run-1/design/Wild/specimen.png" ? "/films/q" : null,
    mediaProject: (filmId: string, source: string) =>
      filmId === FILM && source === ".rasanai/run-1/animatic-mix.wav" ? "/films/q" : null,
    handle: async (command: FilmCommand) => {
      handled.push(command);
      return { ok: true as const, said: "Done" };
    },
  } as unknown as FilmService;
  const provider = {} as RasanaiProvider;
  const media = phoneMedia(provider, films, path.join(dir, "cache"));
  const host = new AddonHost(dir);
  host.register(
    { id: "rasanai", name: "RasanAI", blurb: "" },
    {
      phoneCommands: { film: filmCommand(films) },
      phoneImages: phoneImages(provider, films),
      phoneMedia: {
        ...media,
        prepare: async (source, projectDir) => {
          pictures.push([source, projectDir]);
          return { ok: true, file: { path: mediaFile, mime: "audio/mp4", bytes: 1000 } };
        },
      },
    },
  );
  host.setEnabled("rasanai", true);
  const remote = new RemoteBridge({
    configPath,
    projectId: "squeak-test",
    store: {
      get: async () => null,
      set: async () => {},
      list: async () => [],
      delete: async () => {},
      watch: () => () => {},
    },
    replier: {
      lastTurnText: () => "",
      lastTurnId: () => "t",
      send: async () => ({ status: "started", via: "conductor" }),
    },
    image: async (source, cwd) => {
      pictures.push([source, cwd]);
      return { ok: true, image: { mime: "image/jpeg", data: "AAAA" } };
    },
    addonPhone: host.remotePhone(),
    snapshot: () => ({ sessions: [], active: [] }) as unknown as FleetSnapshot,
    now: () => fixture.madeAt + 1_000,
  });
  return { remote, config, handled, pictures };
}

