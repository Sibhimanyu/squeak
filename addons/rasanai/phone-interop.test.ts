/** A bridge whose add-on is the real RasanAI phone code over a provider that records what it is asked. */
function workflowBridge() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "phone-interop-workflow-"));
  const configPath = path.join(dir, "remote.json");
  const config: RemoteConfig = {
    projectId: "squeak-test",
    channelId: fixture.channelId,
    key: fixture.key,
    devices: [{ id: fixture.deviceId, name: "iPhone", publicKey: fixture.publicKey, pairedAt: "2026-09-25T00:00:00Z" }],
  };
  fs.writeFileSync(configPath, JSON.stringify(config));
  const acts: Array<[string, unknown]> = [];
  const pictures: Array<[string, string]> = [];
  const written: string[] = [];
  const mediaFile = path.join(dir, "copy.m4a");
  fs.writeFileSync(mediaFile, Buffer.alloc(1000, 7));
  const provider = {
    view: () => null,
    allowsImage: (_status: unknown, source: string) => source === ".rasanai/run-1/design/Wild/specimen.png",
    allowsMedia: (_status: unknown, source: string) => source === ".rasanai/run-1/animatic-mix.wav",
    act: (projectDir: string, action: unknown) => {
      acts.push([projectDir, action]);
      return { ok: true as const, actionId: "sq1", said: "Sent" };
    },
  } as unknown as RasanaiProvider;
  const films = {} as FilmService;
  const host = new AddonHost(dir);
  host.register(
    { id: "rasanai", name: "RasanAI", blurb: "" },
    {
      phoneCommands: { workflow: workflowCommand(provider) },
      phoneImages: phoneImages(provider, films),
      phoneMedia: {
        ...phoneMedia(provider, films, path.join(dir, "cache")),
        prepare: async (source, projectDir) => {
          pictures.push([source, projectDir]);
          return { ok: true, file: { path: mediaFile, mime: "audio/mp4", bytes: 1000 } };
        },
      },
    },
  );
  host.setEnabled("rasanai", true);
  const remote = new RemoteBridge({
    configPath,
    projectId: "squeak-test",
    store: {
      get: async () => null,
      set: async (doc: string) => {
        written.push(doc);
      },
      list: async () => [],
      delete: async () => {},
      watch: () => () => {},
    },
    replier: {
      lastTurnText: () => "",
      lastTurnId: () => "turn-1",
      send: async () => ({ status: "started", via: "conductor" }),
    },
    image: async (source, cwd) => {
      pictures.push([source, cwd]);
      return { ok: true, image: { mime: "image/jpeg", data: "AAAA" } };
    },
    addonPhone: host.remotePhone(),
    snapshot: () =>
      ({
        sessions: [],
        active: [
          {
            key: "claude-transcript:d1",
            conductorSessionId: null,
            cwd: "/films/q",
            baseRef: null,
            workflow: { projectDir: "/films/q", step: "look", revision: "look@2026-10-14T16:56:23.780Z" },
          } as unknown as FleetSession,
        ],
      }) as unknown as FleetSnapshot,
    now: () => fixture.madeAt + 1_000,
  });
  return { remote, config, acts, pictures, written };
}

describe.skipIf(!has)("a film command made on the iPhone", () => {
  const signed = (name: string) => ({ id: fixture[`${name}Id`] as string, doc: fixture[name] as Signed });

  it("reaches the films service exactly as the phone signed it", async () => {
    const { remote, config, handled } = bridge();
    const names = [
      "filmSubmitCommand",
      "filmDecideRestCommand",
      "filmCommentCommand",
      "filmRedoCommand",
      "filmChatCommand",
      "filmResumeCommand",
      "filmStopCommand",
      "filmInstallToolCommand",
    ];
    for (const name of names) {
      const { id, doc } = signed(name);
      expect((await remote.handleCommand(config, id, doc)).result).toEqual({ id, status: "sent", said: "Done" });
    }
    const stripped = handled.map((command) => {
      const rest: Partial<FilmCommand> = { ...command };
      delete rest.nonce;
      delete rest.expiresAt;
      return rest;
    });
    expect(stripped).toEqual([
      {
        v: 1,
        kind: "film",
        filmId: FILM,
        op: "answer",
        step: "brief",
        revision: "brief@1",
        type: "submit",
        value: {
          fields: { length_s: 60, aspect: "16:9", subject: "A film about Quotidian", use_brand: true },
          format: { tile: "launch", option: "hero" },
        },
      },
      { v: 1, kind: "film", filmId: FILM, op: "answer", step: "brief", revision: "brief@1", type: "decide-rest" },
      {
        v: 1,
        kind: "film",
        filmId: FILM,
        op: "answer",
        step: "styleframes",
        revision: "styleframes@3",
        type: "comment",
        value: { frame: "f2", text: "Warmer light" },
      },
      {
        v: 1,
        kind: "film",
        filmId: FILM,
        op: "answer",
        step: "styleframes",
        revision: "styleframes@3",
        type: "redo",
        value: { ids: ["f1", "f3"], note: "Less busy" },
      },
      { v: 1, kind: "film", filmId: FILM, op: "chat", text: "Can the title hold longer?" },
      { v: 1, kind: "film", filmId: FILM, op: "resume" },
      { v: 1, kind: "film", filmId: FILM, op: "stop" },
      { v: 1, kind: "film", filmId: FILM, op: "installTool", askId: "2", tool: "ffmpeg" },
    ]);
  });

  it("fetches a film's picture and soundtrack by film id, read in the film's folder", async () => {
    const { remote, config, pictures } = bridge();
    const image = signed("filmImageCommand");
    expect((await remote.handleCommand(config, image.id, image.doc)).result).toMatchObject({
      status: "sent",
      image: { mime: "image/jpeg" },
    });
    const media = signed("filmMediaCommand");
    expect((await remote.handleCommand(config, media.id, media.doc)).result).toMatchObject({
      status: "sent",
      media: { chunks: 1, bytes: 1000 },
    });
    expect(pictures).toEqual([
      [".rasanai/run-1/design/Wild/specimen.png", "/films/q"],
      [".rasanai/run-1/animatic-mix.wav", "/films/q"],
    ]);
  });
});

