// Pure parts of scripts/make-agent-sdk-pin.ts, here so the test can reach them.

export function renderAgentSdkPin(lockText: string, packageText: string): string {
  const lock = JSON.parse(lockText) as { packages: Record<string, { version?: string; integrity?: string }> };
  const pkg = JSON.parse(packageText) as { dependencies?: Record<string, string> };
  const name = "@anthropic-ai/claude-agent-sdk";
  const entry = lock.packages[`node_modules/${name}`];
  if (!entry?.version || !entry.integrity?.startsWith("sha512-"))
    throw new Error(`${name} has no sha512 integrity in package-lock.json`);
  const wanted = pkg.dependencies?.[name];
  if (wanted !== entry.version)
    throw new Error(`package.json pins ${name} at ${wanted}, package-lock.json has ${entry.version}`);
  // sdk.mjs imports only Node built-ins, and Squeak passes its own claude binary, so the one tarball is everything.
  return `// Generated by scripts/make-agent-sdk-pin.ts from package-lock.json. Do not edit; CI checks it.
export const AGENT_SDK_PIN = {
  version: ${JSON.stringify(entry.version)},
  packages: [{ name: ${JSON.stringify(name)}, version: ${JSON.stringify(entry.version)}, integrity: ${JSON.stringify(entry.integrity)} }],
} as const;
`;
}

/** Prettier may re-wrap the generated file: compare without whitespace or trailing commas. */
export function normalizePin(text: string): string {
  return text.replace(/\s+/g, "").replace(/,(?=[\]}])/g, "");
}
