const DOMAIN = "squeak-pond-words-v1";

/** The input, byte for byte: the domain tag, then the owner key, the joiner key and the pond id, each after a newline (UTF-8). */
export function joinWordsInput(ownerKey: string, joinerKey: string, pondId: string): Buffer {
  return Buffer.from(`${DOMAIN}\n${ownerKey}\n${joinerKey}\n${pondId}`, "utf8");
}

/** Three words: the first three bytes of the digest index the list. */
export function joinWords(ownerKey: string, joinerKey: string, pondId: string): [string, string, string] {
  const d = crypto
    .createHash("sha256")
    .update(joinWordsInput(ownerKey, joinerKey, pondId))
    .digest();
  return [JOIN_WORDS[d[0]!]!, JOIN_WORDS[d[1]!]!, JOIN_WORDS[d[2]!]!];
}
